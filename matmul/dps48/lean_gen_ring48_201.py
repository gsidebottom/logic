#!/usr/bin/env python3
"""Generate proof/Mm/Ring_4x4_48_201.lean in the style of Mm/Ring51.lean: the
201-operation rank-48 scheme as a Lean definition on `Matrix (Fin 4) (Fin 4) R`
(a straight-line program of `let`s, commented stage by stage with the
operation counts), and the theorem

    rank48_op201_scheme_eq_mul (h : R) (h2 : 2 * h = 1) (A B) :
        rank48_op201_scheme h A B = A * B

over any commutative ring `R` in which 2 is invertible (`h` is one half).
The entry proofs are `linear_combination e * h2` with the bilinear coefficient
polynomials `e` computed here (exact division by `2h - 1`), reusing the
program analysis of lean_gen48_201.py.

Usage: lean_gen_ring48_201.py PREFIX OUT.lean      (PREFIX_{L,R,P}.slp)
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lean_gen48_201 as G  # noqa: E402
import slp48check as C  # noqa: E402


def main():
    prefix, out = sys.argv[1], sys.argv[2]
    progs = {s: C.parse(open(f"{prefix}_{s}.slp").read()) for s in "LRP"}
    r = len(C.evaluate(progs["L"], 16)[0])
    aname = lambda j: f"A {j // 4} {j % 4}"  # noqa: E731
    bname = lambda j: f"B {j // 4} {j % 4}"  # noqa: E731
    mname = lambda k: f"m{k}"  # noqa: E731
    L = G.Side(progs["L"], 16, aname, "l", False)
    Rs = G.Side(progs["R"], 16, bname, "r", False)
    P = G.Side(progs["P"], r, mname, "c", True)
    total = L.adds + L.scalings + Rs.adds + Rs.scalings + P.adds + P.scalings
    base = prefix.split("/")[-1]

    def let_lines(side, label):
        out_lines = []
        for w, hn, hyp, form, tac in side.wires:
            # hyp is "w = expr"; the expression uses the operands' Lean names
            expr = hyp.split(" = ", 1)[1]
            out_lines.append(f"  let {w} := {expr}")
        return out_lines

    lines = []
    emit = lines.append
    emit(f"""/-
Copyright (c) 2026 Greg Sidebottom. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Greg Sidebottom
-/
import Mathlib.Data.Matrix.Mul
import Mathlib.LinearAlgebra.Matrix.Notation
import Mathlib.Tactic.FinCases
import Mathlib.Tactic.LinearCombination
import Mathlib.Tactic.Ring

/-!
# {total} operations for rank-48 4×4 matrix multiplication over ℤ[1/2]

Machine-checked correctness, in Mathlib's own terms, of the rank-48 scheme
`matmul/dps48/cand48/{base}_{{L,R,P}}` -- a representative of the
Dumas–Pernet–Sedoglavic rational `⟨4×4×4:48⟩` decomposition class whose
three linear programs use **{L.adds + L.scalings} + {Rs.adds + Rs.scalings} + {P.adds + P.scalings} = {total}
operations**, one below R. Patel's 202 and three below the 204 of the
original PLinOpt programs.  The point of the orbit was selected by the
annealer `matmul/dps48/orbit48.py` (operation-floor proxy), the programs by
the value-set large-neighbourhood search `src/bin/lns48.rs` (L and R
directly from matrix-only seeds; the output map through its transpose and
PLinOpt's `transpozer`), and the signs normalized by
`matmul/dps48/signnorm48.py` so that no operation is a negation.
Generated by `matmul/dps48/lean_gen_ring48_201.py`.

Cost model (PLinOpt's, also R. Patel's for this triple): one operation
per binary addition or subtraction and per scaling by a constant other
than ±1 -- here only halvings; copies and sign changes are free.  Counted:
**L: {L.adds} additions + {L.scalings} halvings = {L.adds + L.scalings}; R: {Rs.adds} + {Rs.scalings} = {Rs.adds + Rs.scalings};
output stage: {P.adds} additions = {P.adds + P.scalings}; total {total}.**  The {r} products are
not counted (they are the rank).

The scheme has coefficients in `ℤ[1/2]`, so the statement is over an
arbitrary **commutative** ring `R` with an element `h` such that
`2 * h = 1` (every ring in which 2 is invertible: `ℤ[1/2]`-algebras, all
fields of characteristic ≠ 2); a halving `x / 2` is written `x * h`.
Each product keeps its `A`-factor on the left.

**To run this proof** (force a genuine re-elaboration -- a plain
`lake build` replays the cached result of the last build):

```
cd proof && find .lake/build -name "Ring_4x4_48_201.*" -delete && lake build Mm.Ring_4x4_48_201
```

Expect `Built Mm.Ring_4x4_48_201` (not `Replayed`), followed by the
`#print axioms` line below -- the three standard axioms, no `sorryAx`.
A fresh checkout needs `lake exe cache get` in `proof/` once beforehand.
-/

namespace Ring48_201

variable {{R : Type _}} [CommRing R]

/-- The {total}-operation rank-48 scheme as a straight-line program: `h` is one
half (`2 * h = 1` is assumed by `rank48_op201_scheme_eq_mul`).  Counted
operations: L {L.adds + L.scalings} + R {Rs.adds + Rs.scalings} + output {P.adds + P.scalings} = **{total}**. -/
def rank48_op201_scheme (h : R) (A B : Matrix (Fin 4) (Fin 4) R) :
    Matrix (Fin 4) (Fin 4) R :=
  -- Left factors: the {r} linear forms `L_k · vec(A)` of the scheme's 48×16
  -- matrix L over ℤ[1/2] (entries 0, ±1, ±1/2), computed by {L.adds} additions/
  -- subtractions and {L.scalings} halvings (`* h`) = {L.adds + L.scalings} COUNTED operations.
  -- Rows of L that are a single matrix entry cost nothing (used directly below).""")
    for ln in let_lines(L, "L"):
        emit(ln)
    emit(f"""  -- Right factors: the {r} forms `R_k · vec(B)` of the 48×16 matrix R,
  -- {Rs.adds} additions/subtractions and {Rs.scalings} halvings = {Rs.adds + Rs.scalings} COUNTED operations.""")
    for ln in let_lines(Rs, "R"):
        emit(ln)
    emit(f"  -- The {r} products (the rank; not counted).  A-factor on the left.")
    for k in range(r):
        emit(f"  let m{k} := {L.outputs[k][0]} * {Rs.outputs[k][0]}")
    emit(f"""  -- Output stage: the 16 entries of C from the products, the 16×48 matrix P
  -- (entries 0, ±1), {P.adds} additions/subtractions = {P.adds + P.scalings} COUNTED operations
  -- (found on the transpose P^T, a 48×16 map like L and R, and transposed
  -- back: {P.adds + P.scalings} = {P.adds + P.scalings - 32} + 32 by the transposition principle).""")
    for ln in let_lines(P, "P"):
        emit(ln)
    emit(f"  -- Total: {L.adds + L.scalings} + {Rs.adds + Rs.scalings} + {P.adds + P.scalings} = {total} operations.")
    rows = []
    for i in range(4):
        rows.append(", ".join(P.outputs[4 * i + j][0] for j in range(4)))
    emit("  !![" + ";\n     ".join(rows) + "]")
    emit("")
    # entry proofs
    emit("""-- `rank48_op201_scheme` unfolds to a ~250-binding straight-line program; each
-- entry is one large `linear_combination` goal.
set_option maxHeartbeats 6400000 in
-- Plain `simp` evaluates the concrete `!![..] i j` indexing via Mathlib's
-- matrix simprocs (as in Mm/Ring51.lean).
set_option linter.flexible false in
/-- The scheme computes the matrix product, in Mathlib's own terms, in any
commutative ring where `2 * h = 1`. -/
theorem rank48_op201_scheme_eq_mul (h : R) (h2 : 2 * h = 1)
    (A B : Matrix (Fin 4) (Fin 4) R) :
    rank48_op201_scheme h A B = A * B := by
  simp only [rank48_op201_scheme]
  ext i j
  fin_cases i <;> fin_cases j <;>
    simp [Matrix.mul_apply, Fin.sum_univ_four]""")
    for c in range(16):
        e_out, f_out = P.outputs[c]
        row, col = divmod(c, 4)
        bil = {}
        # RAW forms: the goal is the program inlined, before any use of 2h = 1
        for k, pk in P.outputs_raw[c].items():
            pk_int = pk.get(0, 0)
            for i, fi in L.outputs_raw[k].items():
                for j, gj in Rs.outputs_raw[k].items():
                    prod = G.hp_scale(G.hp_mul(fi, gj), pk_int)
                    bil[(i, j)] = G.hp_add(bil.get((i, j), {}), prod)
        corr_terms = []
        for i in range(16):
            for j in range(16):
                t = 1 if (i // 4 == row and i % 4 == j // 4 and j % 4 == col) else 0
                d = G.hp_add(bil.get((i, j), {}), {0: t}, -1)
                e = G.div_2h_minus_1(d)
                corr_terms += G.lean_hpoly_times(e, f"{aname(i)} * {bname(j)}")
        if corr_terms:
            emit(f"  · linear_combination ({' + '.join(corr_terms)}) * h2")
        else:
            emit("  · ring")
    emit("""
end Ring48_201

-- Axiom audit: a valid proof shows only Lean's standard axioms.
#print axioms Ring48_201.rank48_op201_scheme_eq_mul
""")
    # wrap long lines at term boundaries (Mathlib's 100-column linter)
    import re

    def wrap_long(line, width=100):
        if len(line) <= width:
            return [line]
        indent = len(line) - len(line.lstrip(" "))
        cont = " " * (indent + 4)
        tokens = re.split(r"( \+ |, )", line)
        pieces = ["".join(tokens[i:i + 2]) for i in range(0, len(tokens), 2)]
        parts, cur = [], ""
        for piece in pieces:
            if cur and len(cur) + len(piece) > width:
                parts.append(cur.rstrip())
                cur = cont + piece
            else:
                cur += piece
        parts.append(cur.rstrip())
        return parts

    wrapped = []
    for line in "\n".join(lines).split("\n"):
        wrapped += wrap_long(line)
    open(out, "w").write("\n".join(wrapped))
    print(f"wrote {out}: L {L.adds}+{L.scalings}, R {Rs.adds}+{Rs.scalings}, P {P.adds}+{P.scalings} = {total}; {len(L.wires) + len(Rs.wires) + len(P.wires)} lets, {r} products")


if __name__ == "__main__":
    main()
