#!/usr/bin/env python3
"""Emit the appendix of doc/matmul_4x4_rank48_201ops.tex: the 201-operation
rank-48 scheme's three programs in PLinOpt syntax, three columns per side,
taken verbatim from the sign-normalized triple cand48/p005_201n_{L,R,P}.slp
(the files contributed to PLinOpt as data/4x4x4_48_201_*).  The counts in the
headings are recomputed here with slp48check's evaluator, and the 4096 Brent
equations are re-checked before anything is written.

Usage: mk_paper_appendix48.py [OUT.tex]
       (default doc/matmul_4x4_rank48_201ops_appendix.tex)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import slp48check as C  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(HERE))
PREFIX = os.path.join(HERE, "cand48", "p005_201n")


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "doc", "matmul_4x4_rank48_201ops_appendix.tex")
    texts, progs, counts, mats = {}, {}, {}, {}
    for s, n_in in (("L", 16), ("R", 16), ("P", 48)):
        texts[s] = open(f"{PREFIX}_{s}.slp").read()
        progs[s] = C.parse(texts[s])
        outs, tot = C.evaluate(progs[s], n_in)
        counts[s] = tot
        mats[s] = C.dense(outs, n_in)
    bad = C.brent(mats["L"], mats["R"], mats["P"])
    assert bad == 0, f"{bad} Brent equations fail"
    for s in "LRP":
        assert counts[s][2] == 0, f"{s} has negations"
    total = sum(counts[s][0] + counts[s][1] for s in "LRP")
    assert total == 201, total
    lines = [
        "% generated by matmul/dps48/mk_paper_appendix48.py -- do not edit",
        "The three programs below are the sign-normalized triple stored as",
        "\\path{matmul/dps48/cand48/p005_201n_{L,R,P}.slp} and in PLinOpt as",
        "\\path{data/4x4x4_48_201_{L,R,P}.slp}, in PLinOpt syntax.  In $L$",
        "and $R$ the input \\texttt{i}$(4i{+}j)$ is $a_{ij}$ (resp.\\ $b_{ij}$), indices",
        "from $0$, and output \\texttt{o}$k$ is the factor of product $m_k$",
        "($k=0,\\dots,47$); in $P$ the input \\texttt{i}$k$ is $m_k$ and output",
        "\\texttt{o}$(4i{+}j)$ is $c_{ij}$.  Each line is one operation (a binary",
        "addition or subtraction, or a halving \\texttt{/2}) or a free copy",
        "\\texttt{o}$k$\\texttt{:=}$x$.  The products are $m_k=\\ell_k\\,r_k$ with",
        "$\\ell_k$ the $k$-th output of $L$ (left factor) and $r_k$ that of $R$.",
        f"The generator re-evaluates the programs over $\\mathbb{{Q}}$ and checks all",
        f"$4096$ Brent equations before writing this appendix.",
        "",
    ]
    names = {"L": "Left factors $L$", "R": "Right factors $R$", "P": "Output map $P$"}
    for s in "LRP":
        a, sc, _ = counts[s]
        what = f"{a} additions" + (f" + {sc} halvings" if sc else "") + f" = {a + sc} operations"
        body = [ln.rstrip() for ln in texts[s].splitlines() if ln.strip() and not ln.startswith("#")]
        lines += [
            f"\\subsection*{{{names[s]}: {what}}}",
            "\\begin{multicols}{4}\\scriptsize",
            "\\begin{verbatim}",
            *body,
            "\\end{verbatim}",
            "\\end{multicols}",
            "",
        ]
    open(out, "w").write("\n".join(lines))
    print(f"wrote {out}: L {counts['L'][:2]}, R {counts['R'][:2]}, P {counts['P'][:2]}; total {total}; Brent 0/4096 failures")


if __name__ == "__main__":
    main()
