def parse(path):
    """err[(build, t, n, dist, seed)][plan] = error against the reference"""
    err = collections.defaultdict(dict)
    cur = None
    for line in open(path):
        m = re.match(r"## (\S+) t=(\S) n=(\d+) dist=(\S+) seed=(\d+)", line)
        if m:
            cur = (m.group(1), m.group(2), int(m.group(3)), m.group(4), int(m.group(5)))
            continue
        m = re.match(r"\S+\s+n=\d+\s+f(?:32|64).*plan (\S+).*err64 (\S+)", line)
        if m and cur:
            err[cur][m.group(1)] = float(m.group(2))
    return err


def ratios(err, build, t, plan, n=None, dist=None):
    """error / classical error, one per instance"""
    out = []
    for (b, tt, nn, d, s), r in err.items():
        if b == build and tt == t and (n is None or nn == n) and (dist is None or d == dist) and plan in r and "G" in r:
            out.append(r[plan] / r["G"])
    return out


def cell(v):
    if not v:
        return "--"
    return f"{sum(v) / len(v):.2f}"


