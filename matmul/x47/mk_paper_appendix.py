#!/usr/bin/env python3
"""Emit the 167-XOR paper's appendix from matmul/x47/best/x167: the
scheme (per product, U, V, W as four hex digits, digit i = row i with
bit j = entry (i, j)) and the three programs verbatim.  Re-checks the
scheme (Brent) and the program counts before writing.

Usage: mk_paper_appendix.py [PREFIX] [OUT.tex]
"""
import pathlib
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from scheme47 import brent_ok, load_sms  # noqa: E402

PRE = sys.argv[1] if len(sys.argv) > 1 else str(HERE / "best/x167/x167")
OUT = pathlib.Path(sys.argv[2] if len(sys.argv) > 2
                   else HERE.parents[1] / "doc/matmul_4x4_rank47_xor167_appendix.tex")

U, V, W = load_sms(PRE)
assert brent_ok(U, V, W), "scheme fails Brent"
chk = subprocess.run([sys.executable, str(HERE / "x47check.py"), PRE],
                     capture_output=True, text=True)
assert chk.returncode == 0 and "167 XORs" in chk.stdout, chk.stdout + chk.stderr


def hx(m):
    return "".join("%x" % ((m >> (4 * i)) & 0xF) for i in range(4))


rows = [f"{k + 1:2d}  {hx(u)} {hx(v)} {hx(w)}" for k, (u, v, w) in enumerate(zip(U, V, W))]
third = (len(rows) + 2) // 3
cols = [rows[i:i + third] for i in range(0, len(rows), third)]
lines = []
for i in range(third):
    lines.append("    ".join(c[i] if i < len(c) else "" for c in cols).rstrip())

def prog(side):
    return pathlib.Path(f"{PRE}_{side}.slp").read_text().rstrip("\n")


tex = [
    "% generated by matmul/x47/mk_paper_appendix.py -- do not edit",
    "\\subsection*{A.1\\quad The scheme}",
    "Product $k$ is $m_k=\\langle U_k,A\\rangle\\,\\langle V_k,B\\rangle$ and "
    "$C=\\sum_k m_k W_k$ over $\\F_2$.  Each $4\\times4$ coefficient matrix is "
    "written as four hexadecimal digits, digit $i$ ($i=0,\\dots,3$, left to "
    "right) encoding row $i$ with bit value $2^j$ for entry $(i,j)$; e.g.\\ "
    "\\texttt{1000} is $E_{00}$ and \\texttt{8421} the identity.",
    "\\begin{center}\\footnotesize",
    "\\begin{verbatim}",
    " k  U    V    W        k  U    V    W        k  U    V    W",
    *lines,
    "\\end{verbatim}",
    "\\end{center}",
    "\\subsection*{A.2\\quad The programs}",
    "PLinOpt syntax.  In $L$ and $R$ the inputs \\texttt{i}$4i{+}j$ are "
    "$a_{ij}$ (resp.\\ $b_{ij}$) and output \\texttt{o}$k$ is the operand of "
    "product $k{+}1$; in $P$ the inputs \\texttt{i}$k$ are the products "
    "$m_{k+1}$ and output \\texttt{o}$4i{+}j$ is $c_{ij}$.  A line with $t$ terms "
    "costs $t-1$ XORs; copies (one term) are free.",
    "\\begin{multicols}{3}\\footnotesize",
    "\\noindent $L$: 44 XORs",
    "\\begin{verbatim}",
    prog("L"),
    "\\end{verbatim}",
    "\\noindent $R$: 49 XORs",
    "\\begin{verbatim}",
    prog("R"),
    "\\end{verbatim}",
    "\\noindent $P$: 74 XORs",
    "\\begin{verbatim}",
    prog("P"),
    "\\end{verbatim}",
    "\\end{multicols}",
]
text = "\n".join(tex) + "\n"
assert all(ord(c) < 128 for c in text), "non-ASCII in appendix"
OUT.write_text(text)
print(f"wrote {OUT} ({len(U)} products, {sum(1 for _ in text.splitlines())} lines)")
