//! symflip: a flip graph with a symmetry imposed, over F2.
//!
//! A scheme for <n1 x n2 x n3> is a set of summands a (x) b (x) c (bit masks over the entries of
//! A, B, C).  A triple (X, Y, Z) of invertible matrices acts on it by a -> X a Y^-1, b -> Y b Z^-1,
//! c -> X^-T c Z^T and fixes the matrix multiplication tensor.  The walk stays among the schemes
//! invariant under a group G of such triples: every move is applied to all images at once
//! (Moosbauer and Poole's flip graphs with symmetry, here for symmetries that keep the three slots
//! apart, which rectangular formats have).  Two sources of G:
//!   --gen "S;T;R"   permutations of the three index sets (the standard algorithm is invariant
//!                   under all of them), e.g. "1,2,0;0,1,2,3;1,2,0,4,5,3"; several allowed
//!   --aut           the symmetries of the --start scheme itself, found by running through
//!                   GL_n1 x GL_n2 and solving for Z; --use I,J,.. keeps the subgroup generated by
//!                   those of the listed elements (default: all of them)
//!
//!   flip    s = (a, b, c), t = (a, b', c') share a factor:  s -> (a, b + b', c), t -> (a, b', c' + c).
//!           With symmetry the pairs (g s, g t), g in G, are grouped by their first member: s_i with
//!           partners T_i (several, when s has a larger stabilizer than t), and
//!           s_i -> (a, b + sum_T b', c), t -> (a, b', c' + c) for t in T_i, which preserves the sum.
//!           The move is refused unless the s_i and all partners are distinct summands.
//!   merge   s, t share two factors: s -> (a, b, c + c'), t deleted; with the same grouping.  An orbit
//!           whose members all share two factors merges into one summand fixed by G.
//!   plus    (rank + |orbit|) s = (a, b, c) -> (a, b, v) + (a, b, c + v), v the same factor of another
//!           summand t, applied to the orbit of s, and the new summand flipped at once with t.
//! Zero summands are dropped and equal ones cancel.  The threads share a pool of the schemes of the
//! lowest rank seen.  A walk starts at a pool member (after 1 to --plus-max plus transitions with probability --plus, always if it has no flip), makes
//! random flips, merges whenever it can, makes a further plus transition when flips are scarce or every
//! --plus-every flips (while its rank is within --margin of its start), and ends after --stall flips
//! without a new low of its own.  Whatever it reaches at the pool's rank joins the pool (so the pool
//! diffuses); anything lower replaces it.
//! Every scheme entering the pool at a new low is verified against the tensor and against the group;
//! those at or below --save-at are written (the repository's .bits layout).
//!
//!   symflip N1 N2 N3 [--gen "S;T;R"]... [--start FILE.bits] [--aut [--use I,J,..]] [--list]
//!           [--minutes M] [--threads T] [--seed S] [--stall N] [--plus P] [--plus-max K] [--plus-every N] [--margin K] [--save-at R] [--out DIR]

use std::collections::{HashMap, HashSet};
use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::Mutex;
use std::time::Instant;

type Term = [u32; 3];

struct Rng(u64);
impl Rng {
    fn next(&mut self) -> u64 {
        self.0 = self.0.wrapping_add(0x9e3779b97f4a7c15);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xbf58476d1ce4e5b9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94d049bb133111eb);
        z ^ (z >> 31)
    }
    fn below(&mut self, n: usize) -> usize { (self.next() % n as u64) as usize }
    fn unit(&mut self) -> f64 { (self.next() >> 11) as f64 / 9007199254740992.0 }
}

/// a group element: for each slot, the image of every basis bit (a linear map over F2)
#[derive(Clone, PartialEq, Eq, Hash)]
struct Elem { p: [Vec<u32>; 3] }

fn act(mask: u32, img: &[u32]) -> u32 {
    let (mut m, mut out) = (mask, 0u32);
    while m != 0 { out ^= img[m.trailing_zeros() as usize]; m &= m - 1; }
    out
}
fn apply(g: &Elem, t: &Term) -> Term { [act(t[0], &g.p[0]), act(t[1], &g.p[1]), act(t[2], &g.p[2])] }

/// the map m -> L m R on n x m bit matrices (rows of L: n masks; rows of R: m masks): the image of bit (i', j')
fn sandwich(l: &[u32], r: &[u32], n: usize, m: usize) -> Vec<u32> {
    let mut img = vec![0u32; n * m];
    for ip in 0..n { for jp in 0..m {
        let mut x = 0u32;
        for i in 0..n { if (l[i] >> ip) & 1 == 1 { x |= r[jp] << (i * m); } }
        img[ip * m + jp] = x;
    } }
    img
}
fn mat_inv(a: &[u32], n: usize) -> Option<Vec<u32>> {
    let mut m: Vec<u64> = (0..n).map(|i| a[i] as u64 | (1u64 << (n + i))).collect();
    for c in 0..n {
        let p = (c..n).find(|&r| (m[r] >> c) & 1 == 1)?;
        m.swap(c, p);
        for r in 0..n { if r != c && (m[r] >> c) & 1 == 1 { m[r] ^= m[c]; } }
    }
    Some(m.iter().map(|x| (x >> n) as u32).collect())
}
fn mat_t(a: &[u32], n: usize) -> Vec<u32> { (0..n).map(|i| (0..n).fold(0u32, |x, j| x | (((a[j] >> i) & 1) << j))).collect() }
fn mat_id(n: usize) -> Vec<u32> { (0..n).map(|i| 1u32 << i).collect() }
fn perm_mat(p: &[usize]) -> Vec<u32> { let mut m = vec![0u32; p.len()]; for (i, &pi) in p.iter().enumerate() { m[pi] = 1 << i; } m }   // e_i -> e_p(i)

/// the element of (X, Y^-1, Z^-1): a -> X a Yi, b -> Y b Zi, c -> X^-T c Z^T
fn elem_xyz(n: [usize; 3], x: &[u32], yi: &[u32], zi: &[u32]) -> Elem {
    let (y, z, xi) = (mat_inv(yi, n[1]).unwrap(), mat_inv(zi, n[2]).unwrap(), mat_inv(x, n[0]).unwrap());
    Elem { p: [sandwich(x, yi, n[0], n[1]), sandwich(&y, zi, n[1], n[2]), sandwich(&mat_t(&xi, n[0]), &mat_t(&z, n[2]), n[0], n[2])] }
}
fn compose(a: &Elem, b: &Elem) -> Elem {       // a after b
    Elem { p: [b.p[0].iter().map(|&x| act(x, &a.p[0])).collect(), b.p[1].iter().map(|&x| act(x, &a.p[1])).collect(), b.p[2].iter().map(|&x| act(x, &a.p[2])).collect()] }
}
fn closure(gens: &[Elem], id: Elem) -> Vec<Elem> {
    let mut seen: HashSet<Elem> = HashSet::new();
    let mut out = vec![id.clone()];
    seen.insert(id);
    let mut i = 0;
    while i < out.len() {
        for g in gens { let h = compose(g, &out[i]); if seen.insert(h.clone()) { out.push(h); } }
        i += 1;
        assert!(out.len() <= 5000, "the group is too large");
    }
    out
}
fn order(g: &Elem, id: &Elem) -> usize { let (mut h, mut k) = (g.clone(), 1); while h != *id { h = compose(g, &h); k += 1; } k }

/// the symmetries of a scheme: every X in GL_n1 and Y^-1 in GL_n2 that map the A factors to themselves, then Z^-1 by
/// linear algebra from the summands whose image is decided by the A factor alone
fn automorphisms(s: &[Term], n: [usize; 3]) -> Vec<Elem> {
    assert!(n[0] <= 4 && n[1] <= 4, "--aut runs through GL_n1 x GL_n2: n1, n2 <= 4");
    let gl = |k: usize| -> Vec<Vec<u32>> {
        (0u32..1 << (k * k)).filter_map(|bits| { let m: Vec<u32> = (0..k).map(|i| (bits >> (i * k)) & ((1 << k) - 1)).collect(); mat_inv(&m, k).map(|_| m) }).collect() };
    let (gx, gy) = (gl(n[0]), gl(n[1]));
    let mut acount: HashMap<u32, usize> = HashMap::new();
    for t in s { *acount.entry(t[0]).or_insert(0) += 1; }
    let set: HashSet<Term> = s.iter().copied().collect();
    let mut out = Vec::new();
    let un = n[2] * n[2];
    for x in &gx { for yi in &gy {
        let ia = sandwich(x, yi, n[0], n[1]);
        let mut cnt: HashMap<u32, usize> = HashMap::new();
        if !s.iter().all(|t| { let a = act(t[0], &ia); let c = cnt.entry(a).or_insert(0); *c += 1; acount.get(&a).map_or(false, |&k| *c <= k) }) { continue; }
        // Y b_t Zi = b_s for the summands t whose image s is decided by the A factor: equations in the n3^2 entries of Zi
        let y = mat_inv(yi, n[1]).unwrap();
        let lefty = sandwich(&y, &mat_id(n[2]), n[1], n[2]);
        let mut eqs: Vec<u64> = Vec::new();
        for t in s {
            let a = act(t[0], &ia);
            if acount[&a] != 1 { continue; }
            let tgt = s.iter().find(|u| u[0] == a).unwrap()[1];
            let yb = act(t[1], &lefty);
            for j in 0..n[1] { for k in 0..n[2] {
                let mut row = 0u64;
                for l in 0..n[2] { if (yb >> (j * n[2] + l)) & 1 == 1 { row |= 1u64 << (l * n[2] + k); } }
                if (tgt >> (j * n[2] + k)) & 1 == 1 { row |= 1u64 << un; }
                eqs.push(row);
            } }
        }
        // elimination; free unknowns are run through (few)
        let mut piv: Vec<(usize, u64)> = Vec::new();
        let mut bad = false;
        for mut e in eqs {
            for &(c, r) in &piv { if (e >> c) & 1 == 1 { e ^= r; } }
            if e & ((1u64 << un) - 1) == 0 { if e != 0 { bad = true; break; } continue; }
            let c = (e & ((1u64 << un) - 1)).trailing_zeros() as usize;
            for p in piv.iter_mut() { if (p.1 >> c) & 1 == 1 { p.1 ^= e; } }
            piv.push((c, e));
        }
        if bad { continue; }
        let free: Vec<usize> = (0..un).filter(|c| !piv.iter().any(|p| p.0 == *c)).collect();
        if free.len() > 12 { eprintln!("# --aut: {} free unknowns for Z at one (X, Y), skipped", free.len()); continue; }
        for f in 0u64..1 << free.len() {
            let mut sol = 0u64;
            for (b, &c) in free.iter().enumerate() { if (f >> b) & 1 == 1 { sol |= 1u64 << c; } }
            for &(c, r) in &piv { let v = ((r >> un) & 1) ^ ((r & sol & !(1u64 << c)).count_ones() as u64 & 1); if v == 1 { sol |= 1u64 << c; } }
            let zi: Vec<u32> = (0..n[2]).map(|l| ((sol >> (l * n[2])) & ((1 << n[2]) - 1)) as u32).collect();
            if mat_inv(&zi, n[2]).is_none() { continue; }
            let g = elem_xyz(n, x, yi, &zi);
            if s.iter().all(|t| set.contains(&apply(&g, t))) { out.push(g); }
        }
    } }
    out
}

fn find(s: &[Term], t: &Term) -> Option<usize> { s.iter().position(|x| x == t) }

/// the images of the pair (s, t), grouped by the image of s: None if a summand would be used twice
fn groups(s: &[Term], grp: &[Elem], si: usize, ti: usize) -> Option<Vec<(usize, Vec<usize>)>> {
    let mut out: Vec<(usize, Vec<usize>)> = Vec::new();
    for g in grp {
        let (i, j) = (find(s, &apply(g, &s[si]))?, find(s, &apply(g, &s[ti]))?);
        match out.iter_mut().find(|x| x.0 == i) { Some(x) => { if !x.1.contains(&j) { x.1.push(j); } } None => out.push((i, vec![j])) }
    }
    let firsts: Vec<usize> = out.iter().map(|x| x.0).collect();
    let mut seen: Vec<usize> = Vec::new();
    for (_, js) in &out { for &j in js { if firsts.contains(&j) || seen.contains(&j) { return None; } seen.push(j); } }
    Some(out)
}

/// drop zero summands and cancel equal pairs
fn cleanup(s: &mut Vec<Term>) {
    s.retain(|t| t[0] != 0 && t[1] != 0 && t[2] != 0);
    let mut cnt: HashMap<Term, usize> = HashMap::new();
    for t in s.iter() { *cnt.entry(*t).or_insert(0) += 1; }
    if cnt.values().any(|&c| c > 1) {
        let mut out = Vec::new();
        for (t, c) in cnt { if c % 2 == 1 { out.push(t); } }
        out.sort();
        *s = out;
    }
}

/// the symmetric flip of (si, ti), which share slot x: slot y of the first members gains, slot z of the partners
fn flip(s: &mut Vec<Term>, grp: &[Elem], si: usize, ti: usize, y: usize, z: usize, touched: &mut Vec<usize>) -> bool {
    touched.clear();
    if grp.len() == 1 {
        let (by, cz) = (s[ti][y], s[si][z]);
        s[si][y] ^= by; s[ti][z] ^= cz;
        touched.push(si); touched.push(ti);
        return true;
    }
    let Some(gr) = groups(s, grp, si, ti) else { return false };
    for (i, js) in &gr {
        let add = js.iter().fold(0u32, |m, &j| m ^ s[j][y]);
        let cz = s[*i][z];
        s[*i][y] ^= add;
        touched.push(*i);
        for &j in js { s[j][z] ^= cz; touched.push(j); }
    }
    true
}

/// every merge available, with the symmetry; true if the rank fell
fn reduce(s: &mut Vec<Term>, grp: &[Elem]) -> bool {
    let r0 = s.len();
    'again: loop {
        cleanup(s);
        let r = s.len();
        for a in 0..r { for b in a + 1..r {
            let same = [(s[a][0] == s[b][0]), (s[a][1] == s[b][1]), (s[a][2] == s[b][2])];
            if same.iter().filter(|x| **x).count() != 2 { continue; }
            let z = same.iter().position(|x| !*x).unwrap();
            if let Some(gr) = groups(s, grp, a, b) {
                let mut dead: Vec<usize> = Vec::new();
                for (i, js) in &gr { let add = js.iter().fold(0u32, |m, &j| m ^ s[j][z]); s[*i][z] ^= add; dead.extend(js); }
                dead.sort(); dead.dedup();
                for &d in dead.iter().rev() { s.swap_remove(d); }
                continue 'again;
            }
            // b an image of a: the whole orbit, if all its members share the two factors, becomes one fixed summand
            let orb: Vec<usize> = { let mut o: Vec<usize> = Vec::new(); for g in grp { if let Some(i) = find(s, &apply(g, &s[a])) { if !o.contains(&i) { o.push(i); } } } o };
            if orb.contains(&b) && orb.iter().all(|&i| (0..3).all(|q| q == z || s[i][q] == s[a][q])) {
                let sum = orb.iter().fold(0u32, |m, &i| m ^ s[i][z]);
                let keep = orb[0];
                s[keep][z] = sum;
                let mut dead: Vec<usize> = orb[1..].to_vec();
                dead.sort();
                for &d in dead.iter().rev() { s.swap_remove(d); }
                continue 'again;
            }
        } }
        break;
    }
    s.len() < r0
}

/// a plus transition with the symmetry: the orbit of a random summand s = (a, b, c) is split toward the factor v of
/// another summand t (slot z), s -> (a, b, c + v) + (a, b, v), and the new summand is flipped at once with t, with
/// which it shares v (without the flip the two halves would merge back).  Rank + |orbit of s|; true if done.
fn plus_move(s: &mut Vec<Term>, grp: &[Elem], rng: &mut Rng, touched: &mut Vec<usize>) -> bool {
    for _ in 0..50 {
        let (a, b, z) = (rng.below(s.len()), rng.below(s.len()), rng.below(3));
        if a == b || s[a][z] == s[b][z] { continue; }
        let v = s[b][z];
        // the orbit of a with the images of v; refused if two elements send a to one summand with different v
        let mut plan: Vec<(usize, u32)> = Vec::new();
        let mut ok = true;
        for g in grp {
            let Some(i) = find(s, &apply(g, &s[a])) else { ok = false; break };
            let gv = act(v, &g.p[z]);
            match plan.iter().find(|x| x.0 == i) { Some(x) => { if x.1 != gv { ok = false; break; } } None => plan.push((i, gv)) }
        }
        if !ok { continue; }
        let backup = s.clone();
        let child0 = s.len();                       // the child of a itself: the group's first element is the identity
        for (i, gv) in plan {
            let mut child = s[i];
            child[z] = gv;
            s[i][z] ^= gv;
            s.push(child);
        }
        let distinct = { let mut k = s.clone(); k.sort(); k.windows(2).all(|w| w[0] != w[1]) } && s.iter().all(|t| t[z] != 0);
        let (y1, z1) = if rng.next() & 1 == 0 { ((z + 1) % 3, (z + 2) % 3) } else { ((z + 2) % 3, (z + 1) % 3) };
        if distinct && s[child0][z] == s[b][z] && flip(s, grp, child0, b, y1, z1, touched) { return true; }
        *s = backup;
    }
    false
}

fn tensor_ok(s: &[Term], n: [usize; 3]) -> bool {
    let (nb, nc) = (n[1] * n[2], n[0] * n[2]);
    let mut t = vec![0u8; n[0] * n[1] * nb * nc];
    for x in s {
        let mut a = x[0];
        while a != 0 { let ai = a.trailing_zeros() as usize; a &= a - 1;
            let mut b = x[1];
            while b != 0 { let bi = b.trailing_zeros() as usize; b &= b - 1;
                let mut c = x[2];
                while c != 0 { let ci = c.trailing_zeros() as usize; c &= c - 1; t[(ai * nb + bi) * nc + ci] ^= 1; }
            }
        }
    }
    for i in 0..n[0] { for j in 0..n[1] { for k in 0..n[2] { t[((i * n[1] + j) * nb + j * n[2] + k) * nc + i * n[2] + k] ^= 1; } } }
    t.iter().all(|x| *x == 0)
}
fn invariant(s: &[Term], grp: &[Elem]) -> bool { grp.iter().all(|g| s.iter().all(|t| find(s, &apply(g, t)).is_some())) }
fn fixed(s: &[Term], grp: &[Elem]) -> usize { s.iter().filter(|t| grp.iter().all(|g| apply(g, t) == **t)).count() }

fn standard(n: [usize; 3]) -> Vec<Term> {
    let mut s = Vec::new();
    for i in 0..n[0] { for j in 0..n[1] { for k in 0..n[2] { s.push([1u32 << (i * n[1] + j), 1u32 << (j * n[2] + k), 1u32 << (i * n[2] + k)]); } } }
    s
}

fn write_bits(s: &[Term], n: [usize; 3], path: &str) {
    let sz = [n[0] * n[1], n[1] * n[2], n[0] * n[2]];
    let mut out = String::new();
    for q in 0..3 { for t in s { for k in 0..sz[q] { out.push(if (t[q] >> k) & 1 == 1 { '1' } else { '0' }); } } }
    std::fs::write(path, out + "\n").expect("write");
}
fn read_bits(path: &str, n: [usize; 3]) -> Vec<Term> {
    let txt: Vec<u8> = std::fs::read_to_string(path).expect("start file").bytes().filter(|b| *b == b'0' || *b == b'1').map(|b| b - b'0').collect();
    let sz = [n[0] * n[1], n[1] * n[2], n[0] * n[2]];
    let per = sz[0] + sz[1] + sz[2];
    assert!(txt.len() % per == 0, "not a bits file of this format");
    let r = txt.len() / per;
    let offs = [0, r * sz[0], r * (sz[0] + sz[1])];
    (0..r).map(|m| { let mut t = [0u32; 3]; for q in 0..3 { for k in 0..sz[q] { t[q] |= (txt[offs[q] + m * sz[q] + k] as u32) << k; } } t }).collect()
}

struct Pool { rank: usize, members: Vec<Vec<Term>>, seen: HashSet<Vec<Term>>, written: usize }

fn main() {
    let a: Vec<String> = std::env::args().skip(1).collect();
    if a.len() < 3 { eprintln!("usage: symflip N1 N2 N3 [--gen \"S;T;R\"]... [--start FILE.bits] [--aut [--use I,J,..]] [--list] [--minutes M] [--threads T] [--seed S] [--stall N] [--plus P] [--plus-max K] [--plus-every N] [--margin K] [--save-at R] [--out DIR]"); std::process::exit(2); }
    let n = [a[0].parse::<usize>().unwrap(), a[1].parse::<usize>().unwrap(), a[2].parse::<usize>().unwrap()];
    assert!(n[0] * n[1] <= 32 && n[1] * n[2] <= 32 && n[0] * n[2] <= 32, "a factor does not fit 32 bits");
    let opt = |k: &str, d: f64| -> f64 { a.iter().position(|x| x == k).map(|i| a[i + 1].parse().unwrap()).unwrap_or(d) };
    let (minutes, threads, seed, stall, plus) = (opt("--minutes", 5.0), opt("--threads", 10.0) as usize, opt("--seed", 1.0) as u64, opt("--stall", 20000.0) as u64, opt("--plus", 0.1));
    let plus_max = opt("--plus-max", 2.0) as usize;
    let (plus_every, margin) = (opt("--plus-every", 0.0) as u64, opt("--margin", -1.0));
    let out = a.iter().position(|x| x == "--out").map(|i| a[i + 1].clone());
    let start = match a.iter().position(|x| x == "--start") { Some(i) => read_bits(&a[i + 1], n), None => standard(n) };
    assert!(tensor_ok(&start, n), "the start is not a scheme");
    let id = elem_xyz(n, &mat_id(n[0]), &mat_id(n[1]), &mat_id(n[2]));
    let perm = |s: &str| -> Vec<usize> { s.split(',').map(|x| x.trim().parse().unwrap()).collect() };
    let mut gens = Vec::new();
    for (i, x) in a.iter().enumerate() { if x == "--gen" {
        let p: Vec<&str> = a[i + 1].split(';').collect();
        let (s, t, r) = (perm(p[0]), perm(p[1]), perm(p[2]));
        assert!(s.len() == n[0] && t.len() == n[1] && r.len() == n[2], "a generator's permutations have the wrong lengths");
        // a_(i,j) -> a_(s i, t j): X = P_s, Y^-1 = P_t^T, Z^-1 = P_r^T
        gens.push(elem_xyz(n, &perm_mat(&s), &mat_t(&perm_mat(&t), n[1]), &mat_t(&perm_mat(&r), n[2])));
    } }
    if a.iter().any(|x| x == "--aut") {
        let t0 = Instant::now();
        let auts = automorphisms(&start, n);
        println!("# the start has {} symmetries ({:.0} s):", auts.len(), t0.elapsed().as_secs_f64());
        for (i, g) in auts.iter().enumerate() {
            let inv = auts.iter().position(|h| compose(g, h) == id).unwrap();
            println!("#   {i}: order {}, {} summands fixed, inverse {inv}", order(g, &id), start.iter().filter(|t| apply(g, t) == **t).count());
        }
        match a.iter().position(|x| x == "--use") {
            Some(i) => for k in perm(&a[i + 1]) { gens.push(auts[k].clone()); },
            None => gens.extend(auts),
        }
    }
    let grp = closure(&gens, id);
    let margin = if margin < 0.0 { 2 * grp.len() + 2 } else { margin as usize };
    assert!(invariant(&start, &grp), "the start is not invariant under the group");
    let save_at = opt("--save-at", (start.len() as f64) - 1.0) as usize;
    println!("# symflip <{}x{}x{}>: group of order {}, start of rank {} ({} summands fixed by the group), {minutes} min, {threads} threads, stall {stall}, plus {plus} (every {plus_every} flips, margin {margin}), save at {save_at}",
             n[0], n[1], n[2], grp.len(), start.len(), fixed(&start, &grp));
    if a.iter().any(|x| x == "--list") { return; }
    let t0 = Instant::now();
    let pool = Mutex::new(Pool { rank: start.len(), members: vec![start.clone()], seen: HashSet::new(), written: 0 });
    let (flips_total, walks_total, plus_total) = (AtomicU64::new(0), AtomicU64::new(0), AtomicU64::new(0));
    std::thread::scope(|sc| {
        for th in 0..threads {
            let (grp, pool, out, flips_total, walks_total, plus_total) = (&grp, &pool, &out, &flips_total, &walks_total, &plus_total);
            sc.spawn(move || {
                let mut rng = Rng(seed.wrapping_mul(7919).wrapping_add(th as u64 * 104729 + 1));
                let mut touched: Vec<usize> = Vec::new();
                let (mut flips, mut walks, mut pluses) = (0u64, 0u64, 0u64);
                // a scheme offered to the pool: kept if at or below the pool's rank
                let offer = |s: &Vec<Term>, th: usize| {
                    let mut p = pool.lock().unwrap();
                    if s.len() > p.rank { return; }
                    let mut key = s.clone(); key.sort();
                    if s.len() < p.rank {
                        assert!(tensor_ok(s, n) && invariant(s, grp), "a move broke the scheme or its symmetry");
                        p.rank = s.len(); p.members.clear(); p.seen.clear(); p.written = 0;
                        println!("[thread {th}] rank {} ({} fixed summands) after {:.0} s", s.len(), fixed(s, grp), t0.elapsed().as_secs_f64());
                    }
                    if !p.seen.insert(key) { return; }
                    if p.seen.len() > 200000 { p.seen.clear(); }
                    if p.members.len() < 500 { p.members.push(s.clone()); } else { let k = (s[0][0] as usize ^ p.seen.len()) % 500; p.members[k] = s.clone(); }
                    if s.len() <= save_at && p.written < 20 {
                        if let Some(dir) = out {
                            assert!(tensor_ok(s, n) && invariant(s, grp), "a move broke the scheme or its symmetry");
                            p.written += 1;
                            std::fs::create_dir_all(dir).ok();
                            write_bits(s, n, &format!("{dir}/sym{}_{}x{}x{}_r{}_{}.bits", grp.len(), n[0], n[1], n[2], s.len(), p.written));
                        }
                    }
                };
                while t0.elapsed().as_secs_f64() < minutes * 60.0 {
                    let (mut s, base) = { let p = pool.lock().unwrap(); (p.members[rng.below(p.members.len())].clone(), p.rank) };
                    // plus transitions at the start of a walk: always when no two summands share a factor
                    let stuck = !(0..s.len()).any(|p| (p + 1..s.len()).any(|q| s[p][0] == s[q][0] || s[p][1] == s[q][1] || s[p][2] == s[q][2]));
                    if stuck || rng.unit() < plus {
                        for _ in 0..1 + rng.below(plus_max) { plus_move(&mut s, grp, &mut rng, &mut touched); }
                        reduce(&mut s, grp);
                    }
                    // the walk: flips; a plus transition when flips are scarce (500 tries in a row without a partner) or
                    // every plus_every flips without progress, while the rank stays within `margin` of the walk's start;
                    // it ends after `stall` flips without a new low of its own
                    let cap = s.len().max(base) + margin;
                    let (mut since, mut dry, mut lowest) = (0u64, 0u64, s.len());
                    walks += 1;
                    while since < stall {
                        let (si, x) = (rng.below(s.len()), rng.below(3));
                        // a partner sharing slot x, by reservoir
                        let (mut ti, mut cnt) = (usize::MAX, 0usize);
                        for j in 0..s.len() { if j != si && s[j][x] == s[si][x] { cnt += 1; if rng.below(cnt) == 0 { ti = j; } } }
                        let (y, z) = if rng.next() & 1 == 0 { ((x + 1) % 3, (x + 2) % 3) } else { ((x + 2) % 3, (x + 1) % 3) };
                        if ti == usize::MAX || !flip(&mut s, grp, si, ti, y, z, &mut touched) {
                            dry += 1;
                            if dry < 500 { continue; }
                            dry = 0;
                            if s.len() + grp.len() > cap || !plus_move(&mut s, grp, &mut rng, &mut touched) { break; }
                            pluses += 1; since += 1;
                        } else {
                            dry = 0; flips += 1; since += 1;
                            if plus_every > 0 && since % plus_every == 0 && s.len() + grp.len() <= cap && plus_move(&mut s, grp, &mut rng, &mut touched) { pluses += 1; }
                        }
                        // a move can only create a zero, an equal pair or a mergeable pair at a summand it touched
                        let need = touched.iter().any(|&p| p < s.len() && { let t = s[p]; t[0] == 0 || t[1] == 0 || t[2] == 0 ||
                            s.iter().enumerate().any(|(q, u)| q != p && (t[0] == u[0]) as u8 + (t[1] == u[1]) as u8 + (t[2] == u[2]) as u8 >= 2) });
                        if need && reduce(&mut s, grp) {
                            if s.len() < lowest { lowest = s.len(); since = 0; }
                            if s.len() <= base { offer(&s, th); }
                        }
                    }
                    offer(&s, th);
                }
                flips_total.fetch_add(flips, Ordering::Relaxed);
                walks_total.fetch_add(walks, Ordering::Relaxed);
                plus_total.fetch_add(pluses, Ordering::Relaxed);
            });
        }
    });
    let p = pool.lock().unwrap();
    println!("# done: lowest rank {} ({} schemes in the pool), {:.1} M flips and {:.2} M plus transitions in {} walks, {:.0} s", p.rank, p.members.len(),
             flips_total.load(Ordering::Relaxed) as f64 / 1e6, plus_total.load(Ordering::Relaxed) as f64 / 1e6, walks_total.load(Ordering::Relaxed), t0.elapsed().as_secs_f64());
}
